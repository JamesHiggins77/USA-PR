// Builds js/data/districts.js from real congressional district boundaries.
//
// Source: the @unitedstates/districts project (public domain, from the U.S.
// Census Bureau), 2012 boundaries: https://github.com/unitedstates/districts
// Download each cds/2012/<ST>-<n>/shape.geojson into one folder as <ST>-<n>.json
// (n = 0 for at-large states), then:
//
//   node tools/build_districts.js <geojson folder> <packages dir with d3-geo>
//
// Each district is projected with the same Albers USA projection as the
// state map (us-atlas), simplified, and given an urbanity index from its
// area (small districts are urban).
const path = require('path'), fs = require('fs');
const [src, pkgs] = process.argv.slice(2);
if (!src || !pkgs) { console.error('usage: node tools/build_districts.js <geojson dir> <packages dir>'); process.exit(1); }
const UMD = { 'd3-array': 'd3-array/dist/d3-array.js', 'internmap': 'internmap/dist/internmap.js', 'd3-geo': 'd3-geo/dist/d3-geo.js' };
const cache = {};
function load(name) {
  if (cache[name]) return cache[name];
  const mod = { exports: {} };
  new Function('exports', 'module', 'require', fs.readFileSync(path.join(pkgs, 'nm', UMD[name]), 'utf8'))(mod.exports, mod, load);
  return (cache[name] = mod.exports);
}
const d3 = load('d3-geo');
const proj = d3.geoAlbersUsa().scale(1300).translate([487.5, 305]);

// Douglas-Peucker on projected rings
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let idx = -1, md = 0;
    const [ax, ay] = pts[a], [bx, by] = pts[b], dx = bx - ax, dy = by - ay, L = dx * dx + dy * dy;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i]; let d;
      if (L === 0) d = (px - ax) ** 2 + (py - ay) ** 2;
      else { const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / L)); d = (px - ax - t * dx) ** 2 + (py - ay - t * dy) ** 2; }
      if (d > md) { md = d; idx = i; }
    }
    if (md > tol * tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
function area(r) { let a = 0; for (let i = 0, j = r.length - 1; i < r.length; j = i++) a += (r[j][0] + r[i][0]) * (r[j][1] - r[i][1]); return Math.abs(a / 2); }

const files = fs.readdirSync(src).filter(f => /^[A-Z]{2}-\d+\.json$/.test(f));
const byState = {};
for (const f of files) {
  const [st, num] = f.replace('.json', '').split('-'), n = +num || 1;
  let gj = JSON.parse(fs.readFileSync(path.join(src, f), 'utf8'));
  const geom = gj.type === 'Feature' ? gj.geometry : gj.type === 'FeatureCollection' ? gj.features[0].geometry : gj;
  const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;
  let d = '', tot = 0, cx = 0, cy = 0, big = 0;
  for (const poly of polys) for (const ring of poly) {
    const pr = ring.map(c => proj(c)).filter(Boolean);
    if (pr.length < 3) continue;
    const a = area(pr); tot += a;
    if (a < 0.02) continue; // drop specks (tiny islands)
    const s = simplify(pr, 0.25);
    if (s.length < 3) continue;
    d += 'M' + s.map(p => p[0].toFixed(1) + ',' + p[1].toFixed(1)).join('L') + 'Z';
    if (a > big) { big = a; cx = s.reduce((x, p) => x + p[0], 0) / s.length; cy = s.reduce((y, p) => y + p[1], 0) / s.length; }
  }
  (byState[st] = byState[st] || [])[n - 1] = { d, a: tot, c: [Math.round(cx), Math.round(cy)] };
}
// urbanity: national rank of log(area), smallest = 1
const all = [].concat(...Object.values(byState)).filter(Boolean);
const la = all.map(x => Math.log(x.a + 0.05)), lo = Math.min(...la), hi = Math.max(...la);
const out = {};
for (const st of Object.keys(byState).sort()) {
  const ds = byState[st];
  out[st] = { cells: ds.map(x => x.d), u: ds.map(x => +(1 - (Math.log(x.a + 0.05) - lo) / (hi - lo)).toFixed(2)), c: ds.map(x => x.c) };
}
out.DC = { cells: [null], u: [1], c: [[0, 0]] };
fs.writeFileSync(path.join(__dirname, '../js/data/districts.js'),
  '// Congressional district boundaries (2012, from the @unitedstates/districts project, public domain;\n' +
  '// generated by tools/build_districts.js, do not edit). cells: SVG paths in the state map projection;\n' +
  '// u: urbanity 0..1 from district area; c: centre.\n' +
  '(function (G) { G.USA.DISTRICTS = ' + JSON.stringify(out) + '; })(typeof globalThis !== \'undefined\' ? globalThis : window);\n');
console.log('states', Object.keys(out).length, 'districts', all.length, 'bytes', fs.statSync(path.join(__dirname, '../js/data/districts.js')).size);
